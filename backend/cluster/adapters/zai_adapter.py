import asyncio
from typing import Optional

from .. import cdp
from .base_adapter import BaseAIAdapter

# chat.z.ai (2026+ UI):
#   - Input: textarea#chat-input
#   - Send button: #send-message-button
#   - Assistant message: .markdown-prose (final answer container)
#   - Has a "Thought Process" prefix, which we strip


class ZAIAdapter(BaseAIAdapter):
    def __init__(self):
        super().__init__("zai")

    async def send_prompt(self, ws, prompt_text: str) -> bool:
        focus = """(() => {
            const el = document.querySelector('#chat-input') || document.querySelector('textarea');
            if (!el) return false;
            el.focus();
            return true;
        })()"""
        if not await cdp.evaluate(ws, focus):
            return False

        await cdp.insert_text(ws, prompt_text)
        await asyncio.sleep(0.4)

        click = """(() => {
            const btn = document.querySelector('#send-message-button, [aria-label*="Send" i]');
            if (btn && !btn.disabled) { btn.click(); return true; }
            return false;
        })()"""
        if await cdp.evaluate(ws, click):
            return True

        await cdp.key(ws, "Enter")
        return True

    async def read_response(self, ws, timeout: int = 45) -> Optional[str]:
        script = """(() => {
            const body = document.body.innerText || '';
            if (body.includes('Please complete security verification') || body.includes('drag the slider')) {
                return { answer: 'Please complete security verification', generating: false };
            }
            const nodes = document.querySelectorAll('.markdown-prose');
            const last = nodes[nodes.length - 1];
            if (!last) return { answer: '', generating: false };
            let text = (last.innerText || '').trim();
            // "Thought Process" prefix (strip the reasoning section)
            for (const m of ['Thought Process', 'Thinking...']) {
                const i = text.indexOf(m);
                if (i >= 0) text = text.slice(i + m.length).trim();
            }
            // Strip trailing button labels
            for (const tail of ['\\nConnect IM', '\\nGenerated by AI', '\\nCopy', '\\nShare']) {
                const i = text.indexOf(tail);
                if (i > 0) text = text.slice(0, i).trim();
            }
            const generating = !!document.querySelector('button[aria-label*="Stop" i]');
            return { answer: text, generating };
        })()"""
        return await self.poll_answer(ws, script, timeout=timeout)
