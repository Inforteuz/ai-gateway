-- Database schema v1 (PostgreSQL 16), kept as a migration test fixture.
-- Barcha pul qiymatlari butun son, "mikro-so'm" (1 so'm = 1 000 000 mikro-so'm).
-- Vaqtlar — unix soniya (BIGINT). Bayroqlar — 0/1 butun son (SQLite davridan
-- qolgan kelishuv; kod ularni `=1` bilan solishtiradi).
--
-- Bu fayl faqat migratsiya roli bilan (`python -m app.dbadmin migrate`)
-- bajariladi: ilova roli DDL qila olmaydi. Hamma buyruq idempotent.
-- Sxemani o'zgartirsangiz, `db.py` dagi SCHEMA_VERSION ni oshiring.

-- users.email katta-kichik harfga sezgir emas (SQLite'dagi COLLATE NOCASE o'rnida).
CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public;

CREATE TABLE IF NOT EXISTS schema_meta (
  id      INTEGER PRIMARY KEY CHECK (id = 1),
  version INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         public.citext NOT NULL UNIQUE,
  name          TEXT NOT NULL DEFAULT '',
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
  created_at    BIGINT NOT NULL,
  last_login_at BIGINT,
  -- Ro'yxatdan o'tish paytidagi IP — ko'p akkaunt va bonus farmingini
  -- aniqlash uchun. Keyingi kirishlar `sessions.ip` da qayd etiladi.
  signup_ip     TEXT,
  -- Tashqi kirish usullarining identifikatorlari (Google / Telegram).
  google_sub    TEXT,
  telegram_id   TEXT
);
-- Qismli indeks — NULL qiymatlar ko'p (tashqi kirishdan foydalanmaganlar).
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google ON users(google_sub) WHERE google_sub IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_telegram ON users(telegram_id) WHERE telegram_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS wallets (
  user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  balance    BIGINT NOT NULL DEFAULT 0,   -- haqiqiy qoldiq
  held       BIGINT NOT NULL DEFAULT 0,   -- ishlayotgan so'rovlar uchun band qilingan summa
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  id         TEXT PRIMARY KEY,             -- tokenning sha256 qiymati
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  ip         TEXT,
  user_agent TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS api_keys (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name          TEXT NOT NULL,
  prefix        TEXT NOT NULL,             -- kalitning ko'rsatiladigan boshi
  last4         TEXT NOT NULL,
  key_hash      TEXT NOT NULL UNIQUE,      -- sha256; kalitning o'zi saqlanmaydi
  status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','revoked')),
  rpm_limit     BIGINT,                    -- NULL = umumiy standart
  monthly_limit BIGINT,                    -- NULL = cheklovsiz (mikro-so'm)
  free          BIGINT NOT NULL DEFAULT 0, -- 1 = hisobdan pul yechilmaydi (faqat loglanadi)
  reasoning_effort TEXT,                   -- NULL = umumiy sozlama; none|low|medium|high|model
  created_at    BIGINT NOT NULL,
  last_used_at  BIGINT,
  revoked_at    BIGINT
);
CREATE INDEX IF NOT EXISTS idx_keys_user ON api_keys(user_id);

CREATE TABLE IF NOT EXISTS models (
  id                 TEXT PRIMARY KEY,     -- mijoz ko'radigan nom
  upstream_name      TEXT NOT NULL,        -- Ollama'dagi nom
  display_name       TEXT NOT NULL,
  description        TEXT NOT NULL DEFAULT '',
  price_in_per_1m    BIGINT NOT NULL,      -- 1M kirish tokeni narxi (mikro-so'm)
  price_out_per_1m   BIGINT NOT NULL,      -- 1M chiqish tokeni narxi (mikro-so'm)
  context_window     BIGINT NOT NULL DEFAULT 32768,
  enabled            BIGINT NOT NULL DEFAULT 1,
  created_at         BIGINT NOT NULL,
  provider           TEXT NOT NULL DEFAULT 'local',  -- local = ishxonadagi Ollama; external = tashqi provayder
  refine             BIGINT NOT NULL DEFAULT 0,      -- 1 = javob tashqi model tomonidan tekshiriladi
  listed             BIGINT NOT NULL DEFAULT 1,      -- 0 = ro'yxatda ko'rinmaydi (lekin chaqirsa ishlaydi)
  default_reasoning  TEXT,                           -- NULL = umumiy sozlama
  fallback_price_from TEXT,                          -- tekshiruv ishlamasa, shu model narxi qo'llanadi
  allow_thinking     BIGINT NOT NULL DEFAULT 1       -- 0 = o'ylash (reasoning) har doim o'chiq, mijoz so'rasa ham
);

CREATE TABLE IF NOT EXISTS usage_logs (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id        TEXT NOT NULL UNIQUE,
  user_id           BIGINT NOT NULL REFERENCES users(id),
  key_id            BIGINT REFERENCES api_keys(id),
  model             TEXT NOT NULL,
  endpoint          TEXT NOT NULL,
  prompt_tokens     BIGINT NOT NULL DEFAULT 0,
  completion_tokens BIGINT NOT NULL DEFAULT 0,
  cost              BIGINT NOT NULL DEFAULT 0,
  status_code       BIGINT NOT NULL,
  stream            BIGINT NOT NULL DEFAULT 0,
  estimated         BIGINT NOT NULL DEFAULT 0, -- 1 = token soni taxminiy hisoblangan
  latency_ms        BIGINT,
  ttfb_ms           BIGINT,
  error             TEXT,
  category          TEXT,                      -- NULL = muvaffaqiyatli; aks holda platform|billing|limits|client|cancelled
  reasoning         TEXT,                      -- so'rovga qo'llangan fikrlash darajasi
  refined           TEXT,                      -- tekshiruv natijasi: ok | fallback:<sabab> | partial:<sabab> | NULL
  refine_ms         BIGINT,
  ip                TEXT,
  created_at        BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_usage_user_time ON usage_logs(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_usage_key_time  ON usage_logs(key_id, created_at);
CREATE INDEX IF NOT EXISTS idx_usage_time      ON usage_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_usage_category  ON usage_logs(category, created_at);
-- Bepul modelning kunlik chegarasi: foydalanuvchi + model + bugun bo'yicha tez yig'indi.
CREATE INDEX IF NOT EXISTS idx_usage_user_model_time ON usage_logs(user_id, model, created_at);

-- Bosh kitob: faqat qo'shiladi, hech qachon o'zgartirilmaydi
-- (ilova roliga UPDATE/DELETE huquqi berilmaydi — dbadmin.py ga qarang).
CREATE TABLE IF NOT EXISTS ledger (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL REFERENCES users(id),
  kind          TEXT NOT NULL CHECK (kind IN ('topup','usage','adjustment','refund','bonus')),
  amount        BIGINT NOT NULL,           -- + kirim, - chiqim
  balance_after BIGINT NOT NULL,
  usage_id      BIGINT REFERENCES usage_logs(id),
  note          TEXT NOT NULL DEFAULT '',
  admin_id      BIGINT REFERENCES users(id),
  created_at    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ledger_user ON ledger(user_id, id);
CREATE INDEX IF NOT EXISTS idx_ledger_user_kind ON ledger(user_id, kind);  -- "depozit qilganmi?" tekshiruvi

CREATE TABLE IF NOT EXISTS topup_requests (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES users(id),
  amount       BIGINT NOT NULL,
  note         TEXT NOT NULL DEFAULT '',
  status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  admin_note   TEXT NOT NULL DEFAULT '',
  created_at   BIGINT NOT NULL,
  resolved_at  BIGINT,
  resolved_by  BIGINT REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_topup_status ON topup_requests(status, id);

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Model serveri (ishxonadagi kompyuter) holati: har 30 soniyada bitta yozuv.
CREATE TABLE IF NOT EXISTS health_checks (
  ts         BIGINT NOT NULL,
  state      TEXT NOT NULL,          -- up | tunnel_down | ollama_down
  latency_ms BIGINT,
  error      TEXT
);
CREATE INDEX IF NOT EXISTS idx_health_ts ON health_checks(ts);

-- Uzilishlar (insidentlar): kamida 2 ta ketma-ket muvaffaqiyatsiz tekshiruvdan keyin ochiladi.
CREATE TABLE IF NOT EXISTS incidents (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at BIGINT NOT NULL,
  ended_at   BIGINT,
  reason     TEXT NOT NULL           -- tunnel_down | ollama_down
);
CREATE INDEX IF NOT EXISTS idx_incidents_start ON incidents(started_at);

-- Ommaviy "Sifat namunalari": haqiqiy so'rovlar natijasi (tahrirsiz), admin skripti bilan yangilanadi.
CREATE TABLE IF NOT EXISTS samples (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  position    BIGINT NOT NULL,
  category    TEXT NOT NULL,
  prompt      TEXT NOT NULL,
  fast_model  TEXT NOT NULL,
  fast_answer TEXT NOT NULL,
  fast_ms     BIGINT,
  pro_model   TEXT NOT NULL,
  pro_answer  TEXT NOT NULL,
  pro_ms      BIGINT,
  pro_verified BIGINT NOT NULL DEFAULT 0,
  created_at  BIGINT NOT NULL
);

-- Parolni tiklash havolalari (Telegram orqali yuboriladi).
CREATE TABLE IF NOT EXISTS password_resets (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  used_at    BIGINT,
  request_ip TEXT
);
CREATE INDEX IF NOT EXISTS idx_resets_user ON password_resets(user_id);

-- Klaster provayderlarining holati (cluster_watch.py).
CREATE TABLE IF NOT EXISTS model_health (
  upstream   TEXT PRIMARY KEY,
  state      TEXT NOT NULL,
  since      BIGINT NOT NULL,
  last_check BIGINT NOT NULL,
  detail     TEXT
);

-- Ichki benchmark natijalari (benchmark_run.py yozadi, /portal/benchmark o'qiydi).
CREATE TABLE IF NOT EXISTS benchmark_results (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model       TEXT NOT NULL,
  kategoriya  TEXT NOT NULL,
  jami        BIGINT NOT NULL,
  togri       BIGINT NOT NULL,
  o_rtacha_ms BIGINT,
  yangilandi  BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS benchmark_uniq ON benchmark_results(model, kategoriya);
