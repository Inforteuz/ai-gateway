-- AI Gateway: database schema (PostgreSQL 16).
-- All money values are integers in "micro-UZS" (1 UZS = 1 000 000 micro-UZS).
-- Times are unix seconds (BIGINT). Flags are 0/1 integers (a convention left over
-- from the SQLite days; the code compares them with `=1`).
--
-- This file is run only with the migration role (`python -m app.dbadmin migrate`):
-- the app role cannot run DDL. Every statement is idempotent.
-- If you change the schema, bump SCHEMA_VERSION in `db.py`.

-- users.email is case-insensitive (replaces SQLite's COLLATE NOCASE).
CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public;

CREATE TABLE IF NOT EXISTS schema_meta (
  id      INTEGER PRIMARY KEY CHECK (id = 1),
  version INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         public.citext NOT NULL UNIQUE,
  name          TEXT NOT NULL DEFAULT '',
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
  created_at    BIGINT NOT NULL,
  last_login_at BIGINT,
  -- IP at signup — to detect multiple accounts and bonus farming.
  -- Later logins are recorded in `sessions.ip`.
  signup_ip     TEXT,
  -- Identifiers of external login methods (Google / Telegram).
  google_sub    TEXT,
  telegram_id   TEXT,
  -- Referral program (referral.py). The code is created when first needed.
  -- The index and the upgrade of existing databases are in db.MIGRATIONS[2] (not here:
  -- an index cannot be created while an old database still lacks the column).
  ref_code        TEXT,
  referral_paused BIGINT NOT NULL DEFAULT 0,  -- 1 = an admin paused rewards for this user
  signup_device   TEXT                        -- the browser's `sf_dev` cookie: marks many accounts from one device
);
-- Partial index — many NULLs (users without external login).
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google ON users(google_sub) WHERE google_sub IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_telegram ON users(telegram_id) WHERE telegram_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS wallets (
  user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  balance    BIGINT NOT NULL DEFAULT 0,   -- actual balance
  held       BIGINT NOT NULL DEFAULT 0,   -- amount reserved for in-flight requests
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  id         TEXT PRIMARY KEY,             -- sha256 of the token
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  ip         TEXT,
  user_agent TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS api_keys (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name          TEXT NOT NULL,
  prefix        TEXT NOT NULL,             -- displayed prefix of the key
  last4         TEXT NOT NULL,
  key_hash      TEXT NOT NULL UNIQUE,      -- sha256; this is what authenticates a request
  -- Encrypted copy so the OWNER can look at their own key again (SF_KEY_SECRET lives in
  -- the environment, not here, so a database dump on its own reveals nothing). NULL when
  -- SF_KEY_SECRET is unset, and for keys created before the column existed.
  secret_enc    TEXT,
  status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','revoked')),
  rpm_limit     BIGINT,                    -- NULL = global default
  monthly_limit BIGINT,                    -- NULL = unlimited (micro-UZS)
  free          BIGINT NOT NULL DEFAULT 0, -- 1 = nothing is charged (only logged)
  reasoning_effort TEXT,                   -- NULL = global setting; none|low|medium|high|model
  created_at    BIGINT NOT NULL,
  last_used_at  BIGINT,
  revoked_at    BIGINT
);
CREATE INDEX IF NOT EXISTS idx_keys_user ON api_keys(user_id);

CREATE TABLE IF NOT EXISTS models (
  id                 TEXT PRIMARY KEY,     -- name seen by clients
  upstream_name      TEXT NOT NULL,        -- name in Ollama
  display_name       TEXT NOT NULL,
  description        TEXT NOT NULL DEFAULT '',
  price_in_per_1m    BIGINT NOT NULL,      -- price per 1M input tokens (micro-UZS)
  price_out_per_1m   BIGINT NOT NULL,      -- price per 1M output tokens (micro-UZS)
  context_window     BIGINT NOT NULL DEFAULT 32768,
  enabled            BIGINT NOT NULL DEFAULT 1,
  created_at         BIGINT NOT NULL,
  provider           TEXT NOT NULL DEFAULT 'local',  -- local = on-premises Ollama; external = external provider
  refine             BIGINT NOT NULL DEFAULT 0,      -- 1 = answers are verified by an external model
  listed             BIGINT NOT NULL DEFAULT 1,      -- 0 = hidden from the list (but works when called)
  default_reasoning  TEXT,                           -- NULL = global setting
  fallback_price_from TEXT,                          -- this model's price applies when verification does not run
  allow_thinking     BIGINT NOT NULL DEFAULT 1       -- 0 = thinking (reasoning) always off, even if the client asks
);

CREATE TABLE IF NOT EXISTS usage_logs (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id        TEXT NOT NULL UNIQUE,
  user_id           BIGINT NOT NULL REFERENCES users(id),
  key_id            BIGINT REFERENCES api_keys(id),
  model             TEXT NOT NULL,
  endpoint          TEXT NOT NULL,
  prompt_tokens     BIGINT NOT NULL DEFAULT 0,
  completion_tokens BIGINT NOT NULL DEFAULT 0,
  cost              BIGINT NOT NULL DEFAULT 0,
  status_code       BIGINT NOT NULL,
  stream            BIGINT NOT NULL DEFAULT 0,
  estimated         BIGINT NOT NULL DEFAULT 0, -- 1 = token count is an estimate
  latency_ms        BIGINT,
  ttfb_ms           BIGINT,
  error             TEXT,
  category          TEXT,                      -- NULL = success; otherwise platform|billing|limits|client|cancelled
  reasoning         TEXT,                      -- reasoning level applied to the request
  refined           TEXT,                      -- verification result: ok | fallback:<reason> | partial:<reason> | NULL
  refine_ms         BIGINT,
  ip                TEXT,
  created_at        BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_usage_user_time ON usage_logs(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_usage_key_time  ON usage_logs(key_id, created_at);
CREATE INDEX IF NOT EXISTS idx_usage_time      ON usage_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_usage_category  ON usage_logs(category, created_at);
-- Daily limit on free models: fast sum per user + model + today.
CREATE INDEX IF NOT EXISTS idx_usage_user_model_time ON usage_logs(user_id, model, created_at);

-- Ledger: append-only, never modified
-- (the app role gets no UPDATE/DELETE — see dbadmin.py).
CREATE TABLE IF NOT EXISTS ledger (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL REFERENCES users(id),
  kind          TEXT NOT NULL CHECK (kind IN ('topup','usage','adjustment','refund','bonus','referral')),
  amount        BIGINT NOT NULL,           -- + credit, - debit
  balance_after BIGINT NOT NULL,
  usage_id      BIGINT REFERENCES usage_logs(id),
  note          TEXT NOT NULL DEFAULT '',
  admin_id      BIGINT REFERENCES users(id),
  created_at    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ledger_user ON ledger(user_id, id);
CREATE INDEX IF NOT EXISTS idx_ledger_user_kind ON ledger(user_id, kind);  -- the "has deposited?" check

-- Referral: who invited whom. Written once, at signup only
-- (the app role gets no UPDATE/DELETE — it cannot be re-linked later).
CREATE TABLE IF NOT EXISTS referrals (
  referee_id  BIGINT PRIMARY KEY REFERENCES users(id),   -- the invited user (one person — one referrer)
  referrer_id BIGINT NOT NULL REFERENCES users(id),       -- the inviting user
  method      TEXT NOT NULL,                              -- password | google | telegram
  flags       TEXT NOT NULL DEFAULT '',                   -- flags at signup: same_ip,same_device
  created_at  BIGINT NOT NULL,
  CHECK (referee_id <> referrer_id)
);
CREATE INDEX IF NOT EXISTS idx_referrals_referrer ON referrals(referrer_id, created_at);

-- Referral rewards: at most one row per deposit (ledger.kind='topup').
-- status='skipped' — the reward was not paid (paused by an admin or the referrer is blocked); see `reason`.
CREATE TABLE IF NOT EXISTS referral_rewards (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_id       BIGINT NOT NULL REFERENCES users(id),
  referee_id        BIGINT NOT NULL REFERENCES users(id),
  deposit_ledger_id BIGINT NOT NULL UNIQUE REFERENCES ledger(id),  -- idempotency guarantee
  reward_ledger_id  BIGINT UNIQUE REFERENCES ledger(id),           -- NULL = not paid
  deposit_amount    BIGINT NOT NULL,
  percent_bp        BIGINT NOT NULL,          -- percentage in basis points (5% = 500)
  amount            BIGINT NOT NULL,          -- reward (micro-UZS); the computed value even when skipped
  status            TEXT NOT NULL CHECK (status IN ('paid','skipped')),
  reason            TEXT NOT NULL DEFAULT '',
  created_at        BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ref_rewards_referrer ON referral_rewards(referrer_id, id);

CREATE TABLE IF NOT EXISTS topup_requests (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES users(id),
  amount       BIGINT NOT NULL,
  note         TEXT NOT NULL DEFAULT '',
  status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  admin_note   TEXT NOT NULL DEFAULT '',
  created_at   BIGINT NOT NULL,
  resolved_at  BIGINT,
  resolved_by  BIGINT REFERENCES users(id),
  tg_chat_id   TEXT,               -- Telegram message sent to the owner (topup_telegram.py)
  tg_message_id BIGINT
);
CREATE INDEX IF NOT EXISTS idx_topup_status ON topup_requests(status, id);

-- One row per in-flight request (v5). Admission control reads it inside the write lock:
-- per-key concurrency, the per-key monthly limit and the free daily quota all count
-- pending requests, so parallel requests cannot overshoot. `wallets.held` is a cached
-- SUM(amount) per user; rows of dead processes or past `expires_at` are swept.
CREATE TABLE IF NOT EXISTS reservations (
  request_id  TEXT PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  key_id      BIGINT REFERENCES api_keys(id) ON DELETE CASCADE,
  model       TEXT NOT NULL,
  amount      BIGINT NOT NULL DEFAULT 0,   -- money held in wallets.held for this request
  tokens      BIGINT NOT NULL DEFAULT 0,   -- worst-case tokens (prompt estimate + max output)
  owner       TEXT NOT NULL,               -- app process that admitted the request
  created_at  BIGINT NOT NULL,
  expires_at  BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reservations_key ON reservations(key_id);
CREATE INDEX IF NOT EXISTS idx_reservations_user ON reservations(user_id);

-- Live app processes (heartbeat). Reservations of an owner that stopped beating are released.
CREATE TABLE IF NOT EXISTS app_instances (
  owner      TEXT PRIMARY KEY,
  started_at BIGINT NOT NULL,
  last_seen  BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Model server (on-premises machine) state: one row every 30 seconds.
CREATE TABLE IF NOT EXISTS health_checks (
  ts         BIGINT NOT NULL,
  state      TEXT NOT NULL,          -- up | tunnel_down | ollama_down
  latency_ms BIGINT,
  error      TEXT
);
CREATE INDEX IF NOT EXISTS idx_health_ts ON health_checks(ts);

-- Outages (incidents): opened after at least 2 consecutive failed checks.
CREATE TABLE IF NOT EXISTS incidents (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at BIGINT NOT NULL,
  ended_at   BIGINT,
  reason     TEXT NOT NULL           -- tunnel_down | ollama_down
);
CREATE INDEX IF NOT EXISTS idx_incidents_start ON incidents(started_at);

-- Public "quality samples": real request results (unedited), refreshed by an admin script.
CREATE TABLE IF NOT EXISTS samples (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  position    BIGINT NOT NULL,
  category    TEXT NOT NULL,
  prompt      TEXT NOT NULL,
  fast_model  TEXT NOT NULL,
  fast_answer TEXT NOT NULL,
  fast_ms     BIGINT,
  pro_model   TEXT NOT NULL,
  pro_answer  TEXT NOT NULL,
  pro_ms      BIGINT,
  pro_verified BIGINT NOT NULL DEFAULT 0,
  created_at  BIGINT NOT NULL
);

-- Password reset links (sent via Telegram).
CREATE TABLE IF NOT EXISTS password_resets (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  used_at    BIGINT,
  request_ip TEXT
);
CREATE INDEX IF NOT EXISTS idx_resets_user ON password_resets(user_id);

-- State of cluster providers (cluster_watch.py).
CREATE TABLE IF NOT EXISTS model_health (
  upstream   TEXT PRIMARY KEY,
  state      TEXT NOT NULL,
  since      BIGINT NOT NULL,
  last_check BIGINT NOT NULL,
  detail     TEXT
);

-- Internal benchmark results (written by benchmark_run.py, read by /portal/benchmark).
CREATE TABLE IF NOT EXISTS benchmark_results (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model       TEXT NOT NULL,
  kategoriya  TEXT NOT NULL,
  jami        BIGINT NOT NULL,
  togri       BIGINT NOT NULL,
  o_rtacha_ms BIGINT,
  yangilandi  BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS benchmark_uniq ON benchmark_results(model, kategoriya);

-- Admin action log (instance management, VNC sessions etc.): who, when, what, outcome.
-- Append-only: the app role gets no UPDATE/DELETE (db.NO_DELETE / db.NO_UPDATE).
CREATE TABLE IF NOT EXISTS admin_audit (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  BIGINT NOT NULL,
  admin_id    BIGINT REFERENCES users(id),
  admin_email TEXT NOT NULL,
  action      TEXT NOT NULL,              -- probe | reload | cleanup | cleanup_dry | vnc_open | vnc_session
  target      TEXT NOT NULL DEFAULT '',   -- e.g. "instance:0"
  ok          SMALLINT NOT NULL,          -- 1 = success
  detail      TEXT NOT NULL DEFAULT '',
  ip          TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_admin_audit_target ON admin_audit(target, id);
